  '  name         required. Shown in the app. Any text.',
  '  version      required. Any text, for example "1.0.0".',
  '  description  required. One sentence, shown under the name in Settings.',
  '  author       optional. Your name or handle.',
  '  homepage       optional. A URL.',
  '  api          optional. The addon API version. Use 1.',
  '  main         optional. The entry file. Defaults to "index.js".',
  '',
