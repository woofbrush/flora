/**
 * The addon-authoring prompt.
 *
 * One block of text, offered in Settings with a copy button, written to be
 * pasted into an assistant along with whatever the person wants their addon to
 * do. It lives here rather than in the renderer so it sits in the same folder
 * as the API it documents: when a method is added to `buildApi`, the paragraph
 * that promises it is one file away instead of one repository away.
 *
 * It is deliberately a complete and literal description rather than a summary.
 * The reader is an assistant that has never seen flora and cannot look it up,
 * so anything left out is something it will invent - and an invented method
 * name fails inside a sandbox with no stack trace the author can act on.
 */

